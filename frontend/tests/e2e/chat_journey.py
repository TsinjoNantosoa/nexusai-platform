import asyncio,json
from pathlib import Path
from playwright.async_api import async_playwright

from isolation import assert_isolated_e2e_environment


assert_isolated_e2e_environment()
OUT=Path('/tmp/browser/nexus')
async def main():
 async with async_playwright() as p:
  browser=await p.chromium.launch(headless=True)
  context=await browser.new_context(viewport={'width':1440,'height':1000});page=await context.new_page();errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  await page.goto('http://localhost:8080/login',wait_until='networkidle')
  await page.get_by_role('button',name='Compte de démonstration',exact=True).click()
  await page.get_by_test_id('wallet-balance').wait_for()
  await page.get_by_role('link',name='Explorer',exact=True).first.click()
  await page.get_by_role('heading',name='Avec qui allez-vous créer aujourd’hui ?').wait_for()
  await page.screenshot(path=str(OUT/'explore-desktop-real.png'))
  await page.get_by_role('article').filter(has=page.get_by_role('heading',name='Atlas',exact=True)).get_by_role('link',name='Voir le profil').click()
  await page.get_by_role('button',name='Commencer une conversation',exact=True).click()
  await page.get_by_role('textbox',name='Écrivez votre message…').fill('Aide-moi à organiser une architecture React.')
  await page.get_by_role('button',name='Envoyer',exact=True).click()
  await page.get_by_role('button',name='Arrêter la génération').wait_for(state='hidden')
  await page.locator('.message.assistant').wait_for()
  print('successful messages',await page.locator('.message').count())
  print('balance after message',await page.locator('.chat-side section').first.inner_text())
  await page.screenshot(path=str(OUT/'chat-desktop.png'))
  await page.get_by_label('Scénario de démonstration').select_option('failure')
  await page.get_by_role('textbox',name='Écrivez votre message…').fill('Simulation de panne.')
  await page.get_by_role('button',name='Envoyer',exact=True).click()
  await page.get_by_text('Génération échouée : les 2 gemmes réservées ont été restituées dans la démo.',exact=True).wait_for()
  await page.screenshot(path=str(OUT/'chat-refund.png'))
  print('refund shown',await page.locator('.notice.success').inner_text())
  await context.set_offline(True)
  await page.get_by_text('Vous êtes hors ligne. Paiements et génération IA suspendus.',exact=True).wait_for()
  print('offline send disabled',await page.get_by_role('button',name='Envoyer',exact=True).is_disabled())
  await page.screenshot(path=str(OUT/'chat-offline.png'))
  await context.set_offline(False)
  await page.get_by_text('Vous êtes hors ligne. Paiements et génération IA suspendus.',exact=True).wait_for(state='hidden')
  await page.get_by_role('link',name='Portefeuille',exact=True).first.click()
  await page.get_by_test_id('wallet-balance').wait_for()
  print('balance after refund',await page.get_by_test_id('wallet-balance').inner_text())
  await page.get_by_role('link',name='Paramètres',exact=True).first.click()
  await page.get_by_role('heading',name='Votre espace, vos choix.').wait_for()
  await page.get_by_role('button',name='Se déconnecter',exact=True).last.click()
  await page.get_by_role('heading',name='NexusAI',exact=True).wait_for()
  await page.goto('http://localhost:8080/wallet',wait_until='networkidle')
  print('logout gate',await page.get_by_role('heading',name='Connectez-vous pour accéder à votre espace.').count())
  print('storage',await page.evaluate('({local:localStorage.length, session:sessionStorage.length})'))
  print('service workers',await page.evaluate('navigator.serviceWorker.getRegistrations().then(r=>r.length)'))
  print('errors',json.dumps(errors))
  await browser.close()
asyncio.run(main())
